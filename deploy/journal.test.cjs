const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const {createJournal} = require('./journal.cjs')
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'bebop-journal-'))
const log = createJournal(dir, 150, 2)
for (let i=0; i<10; i++) log('event', {i})
const files = fs.readdirSync(dir)
assert.ok(files.length <= 2)
const rows = files.flatMap(f=>fs.readFileSync(path.join(dir,f),'utf8').trim().split('\n').map(JSON.parse))
assert.ok(rows.some(r=>r.data.i===9))
assert.ok(rows.every(r=>r.time && r.event==='event'))
console.log('journal rotation and latest event: OK')
